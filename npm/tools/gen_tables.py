"""Writes npm/src/tables.js from kaeris/detectors.py, so the JavaScript port reads the very
same patterns and word lists as the Python original and cannot drift by a mistyped character,
and npm/src/plans.js from kaeris/plans.py (the plan numbers the `check` fix line names).

    py -3 npm/tools/gen_tables.py            # rewrite npm/src/tables.js
    py -3 npm/tools/gen_tables.py --check    # exit 1 if it is out of date
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)

from kaeris import detectors as d  # noqa: E402
from kaeris.plans import PLANS  # noqa: E402

OUT = os.path.join(ROOT, "npm", "src", "tables.js")
PLANS_OUT = os.path.join(ROOT, "npm", "src", "plans.js")


def pat(rx):
    return {"source": rx.pattern, "i": bool(rx.flags & re.IGNORECASE)}


def build():
    digits = {chr(k): chr(v) for k, v in d._DIGIT_TRANS.items()}
    t = {
        "PH_RE": pat(d._PH_RE),
        "ICU_SELECTOR_VAR_RE": pat(d._ICU_SELECTOR_VAR_RE),
        "ICU_HEAD_RE": pat(d._ICU_HEAD_RE),
        "NUM_RUN_RE": pat(d._NUM_RUN_RE),
        "DIGITS": digits,
        "NUM_SEP": d._NUM_SEP,
        "MAGNITUDE_SUFFIX_RE": pat(d._MAGNITUDE_SUFFIX_RE),
        "MAGNITUDE_WORD_RE": pat(d._MAGNITUDE_WORD_RE),
        "CJK_MAGNITUDE_RE": pat(d._CJK_MAGNITUDE_RE),
        "CJK_UNITS": d._CJK_UNITS,
        "SUFFIX_MULT": d._SUFFIX_MULT,
        "NUMBER_WORDS": d._NUMBER_WORDS,
        "NUMBER_PART_WORDS": d._NUMBER_PART_WORDS,
        "NUMBER_SCALES": d._NUMBER_SCALES,
        "NUMBER_WORD_RE": pat(d._NUMBER_WORD_RE),
        "NUMBER_RUN_RE": pat(d._NUMBER_RUN_RE),
        "ICU_ARM_LABEL_RE": pat(d._ICU_ARM_LABEL_RE),
        "COUNTER_LANGS": sorted(d._COUNTER_LANGS),
        "INDEFINITE_ARTICLE_RE": pat(d._INDEFINITE_ARTICLE_RE),
        "DOUBLE_ENC_RE": pat(d._DOUBLE_ENC_RE),
        "BROKEN_UNICODE_ESC_RE": pat(d._BROKEN_UNICODE_ESC_RE),
        "TAG_RE": pat(d._TAG_RE),
        "MERGE_MARKER_RE": pat(d._MERGE_MARKER_RE),
        "EMPHASIS_RE": pat(d._EMPHASIS_RE),
        "CLDR_REQUIRED": {k: sorted(v) for k, v in d._CLDR_REQUIRED.items()},
        "REGISTER_MARKERS": {k: [pat(a), pat(b)] for k, (a, b) in d._REGISTER_MARKERS.items()},
        "LANG_EXPANSION": d._LANG_EXPANSION,
        "WRAPS_RE": pat(d._WRAPS_RE),
        "LANG_SCRIPT_RE": {k: pat(v) for k, v in d._LANG_SCRIPT_RE.items()},
        "URL_RE": pat(d._URL_RE),
        "LOWERCASE_WORD_RE": pat(d._LOWERCASE_WORD_RE),
        "CURRENCY_TOKENS": [list(x) for x in d._CURRENCY_TOKENS],
        "CURRENCY_NEAR_NUMBER": [[pat(rx), cur] for rx, cur in d._CURRENCY_NEAR_NUMBER],
        "CURRENCY_ANYWHERE": [[pat(rx), cur] for rx, cur in d._CURRENCY_ANYWHERE],
        "CODE_CURRENCY": d._CODE_CURRENCY,
        "SHORT_LABEL_CHARS": d._SHORT_LABEL_CHARS,
        "SHORT_LABEL_GROWTH": d._SHORT_LABEL_GROWTH,
        "MAX_ICU_DEPTH": d._MAX_ICU_DEPTH,
    }
    body = json.dumps(t, ensure_ascii=True, indent=1, sort_keys=False)
    return ("// Generated by npm/tools/gen_tables.py from kaeris/detectors.py. Do not edit by hand.\n"
            "export default " + body + ";\n")


def build_plans():
    body = json.dumps(PLANS, ensure_ascii=True, indent=1)
    return ("// Generated by npm/tools/gen_tables.py from kaeris/plans.py. Do not edit by hand.\n"
            "export const PLANS = " + body + ";\n")


if __name__ == "__main__":
    outputs = {OUT: build(), PLANS_OUT: build_plans()}
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items()
                 if (open(p, encoding="utf-8", newline="").read() if os.path.exists(p) else "") != text]
        print("\n".join(stale))
        sys.exit(1 if stale else 0)
    for p, text in outputs.items():
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", p)
